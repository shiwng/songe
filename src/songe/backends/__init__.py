"""Lazy backend selection; serving does not import a training framework."""

from contextlib import AbstractContextManager
from typing import Callable, Protocol


class Interrupted(Exception):
    """A work unit was cancelled; only committed checkpoints may be resumed."""


class Backend(Protocol):
    kind: str
    tokenizer: object
    config: object

    def __init__(self, config, check: Callable[[], None], train: bool = True): ...
    def boundary(self): ...
    def base(self) -> AbstractContextManager: ...
    def sample(
        self, prompt_ids, seed=None, *, deterministic=False, max_tokens=None
    ): ...
    def teacher_hidden(self, prompt, y): ...
    def sample_full_length(self, prompt_ids, seed=None): ...
    def compare(self, student_ids, teacher_ids, y, kind) -> float: ...
    def token_logprob(self, *args): ...
    def train_step(self, step, optimizer, seed=None): ...
    def optimizer(self, schedule): ...
    def apply(self, grads, optimizer): ...
    def save(self, path): ...
    def restore(self, path): ...
    def layer_deltas(self, baseline=None) -> list[float]: ...
    def kl_from(self, base, prompt, teacher_prompt, y, *, hindsight=False, views=None) -> float: ...
    def train(self, pool, anchors, work, progress): ...
    def adapter_weights(self): ...
    def scale_delta(self, baseline, trained, scale): ...
    def prepare(self): ...
    def peak_memory(self) -> int: ...
    def reset_peak_memory(self): ...


def kind_for(platform):
    kinds = {a.kind for a in platform.accelerators()}
    return "mlx" if "metal" in kinds else "torch"


def resolve_kind(config, platform):
    if config.backend != "auto":
        return config.backend
    if config.torch_options.get("device", "auto") != "auto":
        return "torch"
    return kind_for(platform)


def choose(config, platform):
    if resolve_kind(config, platform) == "mlx":
        from .mlx import Backend
    else:
        from .torch import Backend
    return Backend
